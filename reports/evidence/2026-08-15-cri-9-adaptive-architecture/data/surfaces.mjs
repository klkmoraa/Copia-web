/**
 * CRI-9 · Catálogo de superficies y su presentación por clase de espacio.
 *
 * Una SUPERFICIE es una unidad de composición con un dueño único y un contrato
 * de presentación. No es un componente React: `ResultsPanel` se reparte aquí
 * entre cuatro superficies distintas, y `Inspector` entre tres.
 *
 * `presentation` usa el vocabulario cerrado del informe §11:
 *   band        · franja fija del shell (TopBar)
 *   dock        · panel acoplado que resta espacio al lienzo (reflow)
 *   inset       · panel superpuesto al borde del lienzo, sin reflow
 *   sheet       · hoja con detents, llega por el borde que CB-6 permita
 *   drawer      · cajón modal sobre el lienzo, con retorno de foco
 *   fullscreen  · sustituye la mesa; conserva y devuelve contexto
 *   overlay     · capa efímera sobre el lienzo (picker, entrada rápida, toast)
 *   floating    · chrome flotante sobre el lienzo, sujeto a CB-3
 *   layer       · dibujo dentro del propio lienzo
 *   none        · no existe en esa clase (debe justificarse)
 */

